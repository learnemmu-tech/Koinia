import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

import {
  accountLast4,
  decryptDonationField,
  encryptDonationField,
  imageBytesMatchDeclaredType,
  inrAmountToPaise,
  isIfscFormat,
  isIndianAccountNumber,
  isUpiIdFormat,
  parseUpiPaymentPayload,
  maskAccountNumber,
  paiseToInrString,
  sameDonationSubmission,
} from "../src/lib/donations/receiving-validation.ts";
import {
  offlineKeyAfterResult,
  offlineSubmissionKey,
} from "../src/lib/donations/offline-submission.ts";
import { roleMeetsMinimum } from "../src/types/membership.ts";

test("only a UPI payment URI is accepted from a QR payload", () => {
  assert.deepEqual(parseUpiPaymentPayload("upi://pay?pa=church.fund@okhdfcbank&pn=Revive%20Church&cu=INR"), {
    upiId: "church.fund@okhdfcbank",
    payeeName: "Revive Church",
  });
  assert.equal(parseUpiPaymentPayload("https://example.com"), null);
  assert.equal(parseUpiPaymentPayload("upi://pay?pa=not-an-id&pn=Name"), null);
  assert.equal(parseUpiPaymentPayload("upi://pay?pa=church.fund@okhdfcbank&cu=USD"), null);
});

test("UPI and bank formats are checked without claiming verification", () => {
  assert.equal(isUpiIdFormat("church.fund@okhdfcbank"), true);
  assert.equal(isUpiIdFormat("not an id"), false);
  assert.equal(isIfscFormat("HDFC0001234"), true);
  assert.equal(isIfscFormat("HDFC1001234"), false);
  assert.equal(isIndianAccountNumber("123456789012"), true);
  assert.equal(maskAccountNumber("123456789012"), "•••• 9012");
  assert.equal(accountLast4("123456789012"), "9012");
});

test("amounts are exact paise and reused keys must match the same gift", () => {
  assert.equal(inrAmountToPaise(500), 50000);
  assert.equal(inrAmountToPaise(10.1), 1010);
  assert.equal(inrAmountToPaise(0), null);
  assert.equal(inrAmountToPaise(10.555), null);
  assert.equal(paiseToInrString(1010), "10.10");
  assert.equal(
    sameDonationSubmission(
      { campaignId: "c1", amount: "10.10", donorEmail: "a@church.test" },
      { campaignId: "c1", amountPaise: 1010, donorEmail: "A@church.test" }
    ),
    true
  );
  assert.equal(
    sameDonationSubmission(
      { campaignId: "c1", amount: "10.10", donorEmail: "a@church.test" },
      { campaignId: "c2", amountPaise: 1010, donorEmail: "a@church.test" }
    ),
    false
  );
});

test("qr bytes must match the declared image type", () => {
  assert.equal(imageBytesMatchDeclaredType("image/png", new Uint8Array([0x89, 0x50, 0x4e, 0x47])), true);
  assert.equal(imageBytesMatchDeclaredType("image/png", new Uint8Array([0xff, 0xd8, 0xff, 0x00])), false);
  assert.equal(imageBytesMatchDeclaredType("image/gif", new Uint8Array([0x47, 0x49, 0x46])), false);
});

test("donation administration follows the church admin role, not editor or member", () => {
  assert.equal(roleMeetsMinimum("church_admin", "church_admin"), true);
  assert.equal(roleMeetsMinimum("org_admin", "church_admin"), true);
  assert.equal(roleMeetsMinimum("editor", "church_admin"), false);
  assert.equal(roleMeetsMinimum("member", "church_admin"), false);
  assert.equal(roleMeetsMinimum("volunteer", "church_admin"), false);
});

test("offline retries keep one key and a confirmed gift can be followed by another", () => {
  const first = offlineSubmissionKey("", () => "key-a");
  const retry = offlineSubmissionKey(first, () => "key-b");
  assert.equal(retry, "key-a");
  assert.equal(offlineKeyAfterResult(retry, false), "key-a");
  assert.equal(offlineKeyAfterResult(retry, true), "");
  const second = offlineSubmissionKey("", () => "key-b");
  assert.equal(second, "key-b");
  assert.notEqual(first, second);
});

test("donation QR keys are generated by the server for one church", () => {
  const source = readFileSync(new URL("../src/lib/donations/church-receiving.ts", import.meta.url), "utf8");
  assert.equal(source.includes("objectKey = `churches/${church.id}/donation-qr/${randomUUID()}"), true);
  assert.equal(source.includes("input.objectKey"), false);
  assert.match(source, /createPresignedGetUrl\(\{ objectKey: object\.key, expiresIn: 120 \}\)/);
  assert.match(source, /expiresIn: 300/);
});

test("account numbers encrypt at rest", () => {
  process.env.DONATION_FIELD_KEY = "test-donation-field-key";
  const encrypted = encryptDonationField("123456789012");
  assert.equal(encrypted.includes("123456789012"), false);
  assert.equal(decryptDonationField(encrypted), "123456789012");
});
